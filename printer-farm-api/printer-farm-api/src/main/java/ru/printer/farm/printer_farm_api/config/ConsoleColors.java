package ru.printer.farm.printer_farm_api.config;

// Простая утилита для цветного вывода в консоль
public class ConsoleColors {
    public static final String RESET = "\033[0m";      // Сброс цвета
    public static final String GREEN = "\033[0;32m";    // Зеленый
    public static final String YELLOW = "\033[0;33m";   // Желтый
    public static final String BLUE = "\033[0;34m";     // Синий
    public static final String PURPLE = "\033[0;35m";   // Фиолетовый
    public static final String CYAN = "\033[0;36m";     // Бирюзовый
}